CREATE TABLE cost_ledger_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP NOT NULL,
    project_id BIGINT,
    provider VARCHAR(64),
    model VARCHAR(128),
    operation VARCHAR(64),
    estimated_usd DOUBLE NOT NULL DEFAULT 0,
    actual_usd DOUBLE,
    status VARCHAR(16) NOT NULL,
    duration_ms BIGINT,
    note VARCHAR(1024)
);

CREATE INDEX idx_cost_ledger_project ON cost_ledger_entry(project_id);
CREATE INDEX idx_cost_ledger_provider ON cost_ledger_entry(provider);
CREATE INDEX idx_cost_ledger_status ON cost_ledger_entry(status);
CREATE INDEX idx_cost_ledger_created ON cost_ledger_entry(created_at);
