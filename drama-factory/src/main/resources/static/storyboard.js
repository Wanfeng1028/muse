  async function api(path, options) {
    const res = await fetch(path, Object.assign({
      headers: { 'Content-Type': 'application/json' }
    }, options || {}));
    if (!res.ok) {
      let msg = _t('sb.requestFailed', '请求失败');
      try {
        const data = await res.json();
        if (data && (data.detail || data.message)) msg = data.detail || data.message;
      } catch (e) {}
      throw new Error(msg);
    }
    if (res.status === 204) return null;
    return res.json();
  }

  function escapeHtml(str) {
    if (str === null || str === undefined) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#39;');
  }

  function statusLine(status, text) {
    const key = String(status || '').toUpperCase();
    const label = text !== undefined && text !== null && text !== ''
      ? String(text)
      : null;
    switch (key) {
      case 'DONE':
        return `<span class="status-pill sp-green">${escapeHtml(label || _t('sb.statusDone', '已完成'))}</span>`;
      case 'PROCESSING':
        return `<span class="status-pill sp-blue">${escapeHtml(label || _t('sb.statusProcessing', '生成中'))}</span>`;
      case 'PENDING':
        return `<span class="status-pill sp-gray">${escapeHtml(label || _t('sb.statusPending', '待提交'))}</span>`;
      case 'FAILED':
        return `<span class="status-pill sp-red">${escapeHtml(label || _t('sb.statusFailed', '失败'))}</span>`;
      default:
        return `<span class="status-pill sp-gray">${escapeHtml(label || _t('sb.statusNone', '未生成'))}</span>`;
    }
  }

