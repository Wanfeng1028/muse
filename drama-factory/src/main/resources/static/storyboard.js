  async function viewScript() {
    const episodeId = getEpisodeId();
    if (!episodeId) { showToast(_t('sb.pickEpisodeFirst', '请先选择剧集')); return; }
    try {
      const scenes = await api('/api/episodes/' + episodeId + '/scenes');
      const body = document.getElementById('viewScriptBody');
      const meta = document.getElementById('viewScriptMeta');
      if (!scenes || !scenes.length) {
        meta.textContent = '';
        body.innerHTML = '<p class="text-secondary m-0">' + escapeHtml(_t('sb.noScriptYet', '本集还没有剧本，先点「AI 生成剧本」或「模板生成」。')) + '<\/p>';
      } else {
        meta.textContent = _t('sb.sceneCount', '共 ') + scenes.length + _t('sb.sceneCountTail', ' 场');
        body.innerHTML = scenes.map(s =>
          '<div class="mb-3"><div class="fw-bold">' + escapeHtml(_t('sb.sceneNoPrefix', '第 ')) + s.sceneNo + escapeHtml(_t('sb.sceneNoSuffix', ' 场')) + ' · '
          + escapeHtml(s.location || '') + ' · ' + escapeHtml(s.timeOfDay || '') + '</div>'
          + '<div class="text-secondary small">' + escapeHtml(_t('sb.sceneVisualPrefix', '画面：')) + escapeHtml(s.description || '') + '</div>'
          + (s.dialogue ? '<div class="small sb-dialogue">' + escapeHtml(s.dialogue) + '</div>' : '')
          + '</div>'
        ).join('');
      }
      const modalEl = document.getElementById('viewScriptModal');
      const modal = tabler.Modal.getOrCreateInstance(modalEl);
      modal.show();
    } catch (e) { showToast(_t('sb.scriptLoadFailed', '剧本加载失败：') + e.message); }
  }
  async function generateScript(mode) {
    const episodeId = getEpisodeId();
    if (!episodeId) { showToast(_t('sb.pickEpisodeFirst', '请先选择剧集')); return; }
    const btn = document.getElementById(mode === 'ai' ? 'aiScriptBtn' : 'tplScriptBtn');
    const orig = btn.textContent;
    btn.disabled = true;
    btn.textContent = _t('sb.generating', '生成中…');
    try {
      const skillSel = document.getElementById('skillSelect');
      const skillId = skillSel && skillSel.value ? skillSel.value : '';
      const url = '/api/episodes/' + episodeId + '/generate-script?mode=' + mode
        + (skillId ? '&skillId=' + encodeURIComponent(skillId) : '');
      const res = await api(url, { method: 'POST' });
      await loadShots();
      const srcLabel = res.source === 'ai' ? _t('sb.sourceAi', 'AI 生成')
        : res.source === 'template-fallback' ? _t('sb.sourceTplFallback', '模板生成（AI 不可用，已自动降级）') : _t('sb.sourceTpl', '模板生成');
      const meta = document.getElementById('scriptMeta');
      meta.hidden = false;
      meta.textContent = _t('sb.thisScript', '本次剧本：') + srcLabel + ' · ' + (res.model || _t('sb.modelTemplate', '模板'))
        + _t('sb.sceneCountPrefix', ' · 共 ') + res.sceneCount + _t('sb.sceneCountSuffix', ' 场') + _t('sb.latencyPrefix', ' · 耗时 ') + (res.latencyMs / 1000).toFixed(1) + 's'
        + (res.usedSkill ? _t('sb.skillPrefix', ' · Skill：') + res.usedSkill : '');
      showToast(_t('sb.scriptGenDone', '剧本生成完成，共 ') + res.sceneCount + _t('sb.scriptGenDoneTail', ' 场（') + srcLabel + _t('sb.scriptGenDoneTail2', '）'));
      viewScript();
    } catch (e) {
      showToast(_t('sb.scriptGenFailed', '剧本生成失败：') + e.message);
    } finally {
      btn.disabled = false;
      btn.textContent = orig;
    }
  }

  async function loadSkillOptions() {
    const sel = document.getElementById('skillSelect');
    if (!sel) return;
    try {
      const list = await api('/api/skills/installed');
      sel.innerHTML = '<option value="">' + escapeHtml(_t('sb.noSkill', '不使用 Skill')) + '</option>';
      (list || []).forEach(function (it) {
        const opt = document.createElement('option');
        opt.value = it.skill.id;
        opt.textContent = it.skill.name + ' v' + it.install.version;
        sel.appendChild(opt);
      });
    } catch (e) { /* 市场不可用时保持默认选项 */ }
  }


  async function loadTasksForShots() {
    state.taskMap = {};
    if (!state.shots.length) return;
    await Promise.all(state.shots.map(async (shot) => {
      const sid = shot.id;
      try {
        const list = await api(`/api/shots/${encodeURIComponent(sid)}/video-tasks`);
        const tasks = Array.isArray(list) ? list : [];
        let latest = null;
        tasks.forEach((t) => {
          if (!latest) { latest = t; return; }
          const ta = t.createdAt || t.id || 0;
          const la = latest.createdAt || latest.id || 0;
          if (ta > la) latest = t;
        });
        state.taskMap[sid] = latest;
      } catch (e) {
        state.taskMap[sid] = null;
      }
    }));
  }

  function taskForShot(shotId) {
    return (state.taskMap && state.taskMap[shotId]) || null;
  }

  function toTimecode(seconds) {
    const total = Math.max(0, Math.round(Number(seconds) || 0));
    const mm = String(Math.floor(total / 60)).padStart(2, '0');
    const ss = String(total % 60).padStart(2, '0');
    return `${mm}:${ss}`;
  }

  function renderShots() {
    const grid = document.getElementById('slateGrid');
    if (!grid) return;

    const pid = getProjectId();
    const eid = getEpisodeId();

    if (!pid || !eid) {
      grid.innerHTML = '<div class="alert alert-info">' + escapeHtml(_t('sb.emptyPick', '请选择项目与剧集')) + '</div>';
      return;
    }

    if (!state.shots.length) {
      grid.innerHTML = '<div class="alert alert-info">' + escapeHtml(_t('sb.emptyShots', '本集暂无分镜，点击“添加分镜”新建')) + '</div>';
      return;
    }

    const lastIndex = state.shots.length - 1;

    grid.innerHTML = state.shots.map((shot, index) => {
      const no = String(index + 1).padStart(2, '0');
      const sizeLabel = shot.shotSizeLabel || SHOT_SIZE_LABEL[shot.shotSize] || shot.shotSize || '';
      const moveLabel = shot.cameraMoveLabel || CAMERA_MOVE_LABEL[shot.cameraMove] || shot.cameraMove || '';
      const task = taskForShot(shot.id);
      const vStatus = task ? task.status : null;

      const metaParts = [];
      if (sizeLabel) metaParts.push(escapeHtml(sizeLabel));
      if (moveLabel) metaParts.push(escapeHtml(moveLabel));
      metaParts.push(escapeHtml(_t('sb.duration', '时长') + ' ' + toTimecode(shot.durationSeconds)));
      const metaHtml = `<div class="shot-meta">${metaParts.join(' · ')}</div>`;

      const descHtml = shot.description
        ? `<div class="shot-desc">${escapeHtml(shot.description)}</div>`
        : '';
      const dialogueHtml = shot.dialogue
        ? `<div class="shot-sub">${escapeHtml(_t('sb.dialogueLabel', '对白：'))}${escapeHtml(shot.dialogue)}</div>`
        : '';

      const statusText = task
        ? (task.statusLabel || task.status || _t('sb.statusUnknown', '未知'))
        : null;

      const upDisabled = index === 0 ? ' disabled' : '';
      const downDisabled = index === lastIndex ? ' disabled' : '';

      return `
<div class="shot-row" data-sid="${escapeHtml(shot.id)}">
  <div class="shot-no">${escapeHtml(no)}</div>
  <div class="shot-main">
    ${descHtml}
    ${dialogueHtml}
    ${metaHtml}
  </div>
  <div class="shot-side">
    ${statusLine(vStatus, statusText)}
    <div class="shot-actions">
      <button class="btn btn-sm btn-quiet" data-act="up"${upDisabled}>${escapeHtml(_t('sb.up', '上移'))}</button>
      <button class="btn btn-sm btn-quiet" data-act="down"${downDisabled}>${escapeHtml(_t('sb.down', '下移'))}</button>
      <button class="btn btn-sm btn-quiet" data-act="edit">${escapeHtml(_t('c.edit', '编辑'))}</button>
      <button class="btn btn-sm btn-quiet" data-act="del">${escapeHtml(_t('c.delete', '删除'))}</button>
      <button class="btn btn-sm btn-secondary" data-act="gen">${escapeHtml(_t('sb.gen', '生成视频'))}</button>
    </div>
  </div>
</div>`;
    }).join('');

    if (window.DFI18N) DFI18N.applyI18n(grid);
  }

