package com.dramafactory.config;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.web.servlet.MockMvc;

import static org.hamcrest.Matchers.not;
import static org.hamcrest.Matchers.emptyOrNullString;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.header;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * RequestIdFilter 集成测试。
 *
 * <p>覆盖 request_id 机制的三个关键行为：
 * <ol>
 *   <li>请求未携带 X-Request-Id 时，自动生成一个非空 ID 并写回响应头；</li>
 *   <li>请求携带 X-Request-Id 时，原样透传并写回响应头；</li>
 *   <li>发生异常时，ErrorResponse 中的 requestId 字段与响应头保持一致。</li>
 * </ol>
 *
 * <p>使用 @SpringBootTest + @AutoConfigureMockMvc 加载完整上下文（含过滤器链、
 * 全局异常处理器等），测试环境配置沿用 src/test/resources/application.yml。
 */
@SpringBootTest
@AutoConfigureMockMvc
class RequestIdFilterTest {

    /** 请求头名称，与 RequestIdFilter 中保持一致。 */
    private static final String HEADER_NAME = "X-Request-Id";

    @Autowired
    private MockMvc mockMvc;

    /**
     * 场景 1：请求未携带 X-Request-Id。
     * 期望：HTTP 200，且响应头 X-Request-Id 存在且非空（由过滤器自动生成的 UUID）。
     */
    @Test
    void testAutoGeneratedRequestId() throws Exception {
        mockMvc.perform(get("/api/health"))
                .andExpect(status().isOk())
                // 响应头必须存在，且不为空字符串
                .andExpect(header().string(HEADER_NAME, not(emptyOrNullString())));
    }

    /**
     * 场景 2：请求携带 X-Request-Id: test-123。
     * 期望：HTTP 200，且响应头 X-Request-Id 原样回写为 test-123。
     */
    @Test
    void testPropagatedRequestId() throws Exception {
        mockMvc.perform(get("/api/health").header(HEADER_NAME, "test-123"))
                .andExpect(status().isOk())
                // 透传：响应头应等于请求头传入的值
                .andExpect(header().string(HEADER_NAME, "test-123"));
    }

    /**
     * 场景 3：请求携带 X-Request-Id: err-456 访问不存在的任务。
     * 期望：HTTP 404，响应体 ErrorResponse 的 requestId 字段为 err-456，
     * 且响应头 X-Request-Id 也为 err-456（保证链路追踪 ID 一致）。
     */
    @Test
    void testErrorResponseContainsRequestId() throws Exception {
        mockMvc.perform(get("/api/video-tasks/999999").header(HEADER_NAME, "err-456"))
                .andExpect(status().isNotFound())
                // 响应体中的 requestId 字段应等于请求头传入的 ID
                .andExpect(jsonPath("$.requestId").value("err-456"))
                // 响应头同样回写该 ID
                .andExpect(header().string(HEADER_NAME, "err-456"));
    }
}
