// setEnv 设置环境变量并在测试结束后恢复。
func setEnv(t *testing.T, key, value string) {
	t.Helper()
	old, existed := os.LookupEnv(key)
	if err := os.Setenv(key, value); err != nil {
		t.Fatalf("设置环境变量 %s 失败: %v", key, err)
	}
	t.Cleanup(func() {
		if existed {
			_ = os.Setenv(key, old)
		} else {
			_ = os.Unsetenv(key)
		}
	})
}

// unsetEnv 删除环境变量并在测试结束后恢复。
func unsetEnv(t *testing.T, key string) {
	t.Helper()
	old, existed := os.LookupEnv(key)
	if err := os.Unsetenv(key); err != nil {
		t.Fatalf("删除环境变量 %s 失败: %v", key, err)
	}
	t.Cleanup(func() {
		if existed {
			_ = os.Setenv(key, old)
		} else {
			_ = os.Unsetenv(key)
		}
	})
}

// clearAllEnv 清空本包所有相关环境变量，保证测试之间不互相污染。
func clearAllEnv(t *testing.T) {
	t.Helper()
	keys := []string{
		envAddr, envDB, envAdminKey, envBaseURL,
		envRateLimitRPS, envRateLimitBurst, envRateLimitEnabled,
		envBurnPurgeAfterDestroy,
		envPurgeInterval, envPurgeRetentionDays,
		envBackupDir, envBackupMaxAgeDays,
		envPasswordFailAlertThreshold, envPasswordFailAlertWindow, envAlertWebhookURL,
	}
	for _, k := range keys {
		unsetEnv(t, k)
	}
}

// TestFromEnvDefaults 检查全部缺省值，确保默认配置可预期。
func TestFromEnvDefaults(t *testing.T) {
	clearAllEnv(t)

	cfg := FromEnv()

	if cfg.Addr != ":8080" {
		t.Fatalf("Addr 默认值错误，want :8080，got %q", cfg.Addr)
	}
	if cfg.DBPath != "./data/linkshort.db" {
		t.Fatalf("DBPath 默认值错误，want ./data/linkshort.db，got %q", cfg.DBPath)
	}
	if cfg.RateLimitRPS != 20 {
		t.Fatalf("RateLimitRPS 默认值错误，want 20，got %v", cfg.RateLimitRPS)
	}
	if cfg.RateLimitBurst != 40 {
		t.Fatalf("RateLimitBurst 默认值错误，want 40，got %d", cfg.RateLimitBurst)
	}
	if !cfg.RateLimitEnabled {
		t.Fatalf("RateLimitEnabled 默认值错误，want true，got %v", cfg.RateLimitEnabled)
	}
	if cfg.BurnPurgeAfterDestroy {
		t.Fatalf("BurnPurgeAfterDestroy 默认值错误，want false，got %v", cfg.BurnPurgeAfterDestroy)
	}
	if cfg.PurgeInterval != 24*time.Hour {
		t.Fatalf("PurgeInterval 默认值错误，want 24h，got %v", cfg.PurgeInterval)
	}
	if cfg.PurgeRetentionDays != 7 {
		t.Fatalf("PurgeRetentionDays 默认值错误，want 7，got %d", cfg.PurgeRetentionDays)
	}
	if cfg.BackupDir != "./backups" {
		t.Fatalf("BackupDir 默认值错误，want ./backups，got %q", cfg.BackupDir)
	}
	if cfg.BackupMaxAgeDays != 7 {
		t.Fatalf("BackupMaxAgeDays 默认值错误，want 7，got %d", cfg.BackupMaxAgeDays)
	}
	if cfg.PasswordFailAlertThreshold != 10 {
		t.Fatalf("PasswordFailAlertThreshold 默认值错误，want 10，got %d", cfg.PasswordFailAlertThreshold)
	}
	if cfg.PasswordFailAlertWindow != 5*time.Minute {
		t.Fatalf("PasswordFailAlertWindow 默认值错误，want 5m，got %v", cfg.PasswordFailAlertWindow)
	}
	if cfg.AlertWebhookURL != "" {
		t.Fatalf("AlertWebhookURL 默认值错误，want 空，got %q", cfg.AlertWebhookURL)
	}
	if cfg.BaseURL != "" {
		t.Fatalf("BaseURL 默认值错误，want 空，got %q", cfg.BaseURL)
	}
}

// TestFromEnvAdminKeyAutoGenerated 检查未设置时自动生成 32 位 hex 密钥。
func TestFromEnvAdminKeyAutoGenerated(t *testing.T) {
	clearAllEnv(t)

	cfg := FromEnv()

	if cfg.AdminKey == "" {
		t.Fatalf("AdminKey 未设置时应自动生成，实际为空")
	}
	if len(cfg.AdminKey) != 32 {
		t.Fatalf("AdminKey 应为 32 位 hex，实际长度 %d，值 %q", len(cfg.AdminKey), cfg.AdminKey)
	}
	for _, r := range cfg.AdminKey {
		if !strings.ContainsRune("0123456789abcdef", r) {
			t.Fatalf("AdminKey 含非 hex 字符 %q，值 %q", r, cfg.AdminKey)
		}
	}

	cfg2 := FromEnv()
	if cfg2.AdminKey == "" {
		t.Fatalf("第二次生成 AdminKey 为空")
	}
	if len(cfg2.AdminKey) != 32 {
		t.Fatalf("第二次生成 AdminKey 长度错误，got %d", len(cfg2.AdminKey))
	}
}

