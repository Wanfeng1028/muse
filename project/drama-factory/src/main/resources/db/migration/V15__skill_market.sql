CREATE TABLE skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(200) NOT NULL UNIQUE,
    description VARCHAR(1000),
    author VARCHAR(200) NOT NULL DEFAULT '官方',
    category VARCHAR(50) NOT NULL,
    tags VARCHAR(500),
    icon VARCHAR(50),
    official BOOLEAN DEFAULT FALSE,
    install_count BIGINT DEFAULT 0,
    rating_sum BIGINT DEFAULT 0,
    rating_count BIGINT DEFAULT 0,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);
CREATE INDEX idx_skill_category ON skills(category);

CREATE TABLE skill_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id BIGINT NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    version VARCHAR(50) NOT NULL,
    prompt_template CLOB NOT NULL,
    changelog VARCHAR(1000),
    created_at TIMESTAMP,
    UNIQUE (skill_id, version)
);

CREATE TABLE skill_installs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id BIGINT NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    version VARCHAR(50) NOT NULL,
    installed_at TIMESTAMP,
    UNIQUE (skill_id)
);

CREATE TABLE skill_ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id BIGINT NOT NULL REFERENCES skills(id) ON DELETE CASCADE,
    score INT NOT NULL,
    comment VARCHAR(1000),
    created_at TIMESTAMP
);

ALTER TABLE agent_steps ADD COLUMN skill_id BIGINT;

