_PENTA = [0, 2, 4, 7, 9]


def _shimmer(rng, seed, pitch=0.0, bright=0.5, dur=1.2, density=0.5, root='D'):
    r = midi(root + '6') + pitch
    notes = [r + o + 12 * k for k in (0, 1) for o in _PENTA]
    n = smp(dur)
    out = np.zeros((2, n + smp(0.25)))
    t = 0.0
    while True:
        rate = (10.0 + 30.0 * density) * np.exp(-t / (0.5 * dur)) + 3.0
        t += float(rng.exponential(1.0 / rate))
        if t >= dur - 0.05:
            break
        m = notes[int(rng.integers(len(notes)))]
        g = ins.grain(hz(m) * (1 + rng.uniform(-0.0015, 0.0015)), float(rng.uniform(0.05, 0.16)),
                      float(rng.uniform(0.55, 1.0)) * np.exp(-t / (0.7 * dur)), 1.0, 0.0, 0.1)
        s0 = smp(t)
        seg = stereo(g, float(rng.uniform(-0.85, 0.85)))
        out[:, s0:s0 + seg.shape[1]] += seg[:, : out.shape[1] - s0]
    air = hp(noise(n, seed * 41 + 3), 6000, 2)
    air = lp(air, 11000, 2) * np.sin(np.pi * np.linspace(0, 1, n)) ** 2 * (0.02 + 0.06 * bright)
    out[:, :n] += np.vstack([air, np.roll(air, 480)])
    return _space(out, 0.4, 'hall', tail=0.8)


