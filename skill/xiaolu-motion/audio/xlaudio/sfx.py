def _impact_soft(rng, seed, pitch=0.0, bright=0.5, dur=0.6):
    r = semis(pitch)
    n = smp(dur)
    t = np.arange(n) / SR
    body = np.sin(TWOPI * np.cumsum(110.0 * r * (1 + 0.5 * np.exp(-t / 0.012))) / SR) * _att(t, 0.001) * np.exp(-t / 0.12)
    thud = ins.boom(70.0 * r, 48.0 * r, dur, 1.0, glide_tau=0.12, decay=dur * 0.3, sat=1.1)
    out = np.zeros((2, n))
    for ch in range(2):
        nz = lp(noise(n, seed * 19 + ch), 900.0 + 2500.0 * bright, 2) * _att(t, 0.0008) * np.exp(-t / 0.035)
        out[ch] = 0.6 * thud + 0.5 * body + 0.35 * nz
    return out


