def _b(bright, span=1.6):
    """brightness 0..1 -> frequency multiplier 2^((b-0.5)*span)."""
    return 2.0 ** ((bright - 0.5) * span)


def _space(y, amount, ir='plate', tail=1.0):
    """add a synthetic plate/room/hall reverb (returns stereo, length + tail)."""
    y = dual_mono(y) if y.ndim == 1 else y
    if amount <= 0:
        return y
    n = y.shape[1] + smp(tail)
    dry = np.hstack([y, np.zeros((2, n - y.shape[1]))])
    wet = convolve_st(hp(dry, 200, 2), get_ir(ir), n)
    out = dry + amount * wet * 0.35
    nf = min(n // 2, smp(0.25))
    out[:, -nf:] *= rc_ramp(nf)[::-1]
    return out


def _note(p, default):
    base = p.get('note') or default
    return midi(base) + p.get('pitch', 0.0)


