"""Sound-effect catalogue: ``render_sfx(id, **params) -> (2, n) float64 @ 48 kHz``.

Every effect is a registered ``SfxSpec``: a generator plus metadata (purpose,
suggested sync, anchor point, parameter ranges, reference level). All effects
share the same parameter vocabulary where it makes sense:

* ``pitch``  semitones relative to the effect's native tuning
* ``bright`` 0..1 timbre brightness (filter cut-off / FM index / air layer)
* ``dur``    seconds (overall length or decay length, see the catalogue)
* ``seed``   int; the same (id, params, seed) always renders the same samples

Reference level ("统一响度归一"): after rendering, every effect is normalised
to its class reference, either a true-peak target (``tp``, dBTP, short
transients) or a max-momentary-loudness target (``mmax``, LUFS over a 400 ms
window, sustained sounds). The references are designed for a voice track at
-16 LUFS integrated; the master stage moves everything together, so gain_db = 0
in a cue means "sits at its designed level against speech". See
sfx/CATALOG.md (generated by ``python cli.py catalog``).
"""
import warnings
import zlib
from dataclasses import dataclass, field

import numpy as np

