def _stamp(rng, seed, pitch=0.0, bright=0.5):
    r = semis(pitch)
    y = ins.stamp(1.0, seed=seed * 37 + 1, f=70.0 * r, paper=0.2 + 0.4 * bright)
    t = np.arange(len(y)) / SR
    y += 0.3 * np.sin(TWOPI * 165.0 * r * t) * _att(t, 0.001) * np.exp(-t / 0.018)
    return y


