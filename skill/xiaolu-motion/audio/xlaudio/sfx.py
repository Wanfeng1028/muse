def _impact_big(rng, seed, pitch=0.0, bright=0.5, dur=1.8, tail=0.5):
    r = semis(pitch)
    n = smp(dur)
    t = np.arange(n) / SR
    b = ins.boom(50.0 * r, 35.0 * r, dur, 1.0)
    body = np.sin(TWOPI * np.cumsum(95.0 * r * (1 + 0.6 * np.exp(-t / 0.015))) / SR) * _att(t, 0.001) * np.exp(-t / 0.16)
    out = np.zeros((2, n))
    for ch in range(2):
        nz = lp(noise(n, seed * 23 + ch), 1400.0 + 2000.0 * bright, 2) * _att(t, 0.0008) * np.exp(-t / 0.18)
        crash = lp(hp(noise(n, seed * 23 + 7 + ch), 3500.0, 2), 7000.0 + 4000.0 * bright, 2)
        crash *= _att(t, 0.0005) * np.exp(-t / (0.2 + 0.4 * tail)) * (0.03 + 0.07 * tail * (0.5 + bright))
        out[ch] = 0.9 * b + 0.55 * body + 0.32 * nz + crash
    out[:, :24] *= rc_ramp(24)
    return _space(out, 0.35 * tail, 'room', tail=0.6)


