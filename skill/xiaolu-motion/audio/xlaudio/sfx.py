def _glitch(rng, seed, pitch=0.0, bright=0.5, dur=0.3, density=0.5):
    r = semis(pitch)
    n = smp(dur)
    os_ = 4
    out = np.zeros((2, n))
    t = 0.0
    k = 0
    while t < dur - 0.006:
        seg = float(rng.uniform(0.008, 0.045) * (1.3 - 0.8 * density))
        seg = min(seg, dur - t)
        m = smp(seg)
        if m < 64:
            break
        kind = rng.choice(['buzz', 'noise', 'fm', 'sh', 'gap'], p=[0.26, 0.2, 0.2, 0.22, 0.12])
        tt = np.arange(m) / SR
        if kind == 'buzz':          # band-limited square at a random pitch
            f = float(rng.uniform(180, 900)) * r
            y = np.zeros(m)
            for h in range(1, 60, 2):
                if f * h > 11000 * (0.6 + 0.8 * bright):
                    break
                y += np.sin(TWOPI * f * h * tt) / h
            y *= 0.8
        elif kind == 'noise':
            y = bpf(noise(m, seed * 31 + k), 800.0 * r, min(3000.0 + 9000.0 * bright, 20000.0), 2)
        elif kind == 'fm':
            f = float(rng.uniform(300, 2400)) * r
            y = np.sin(TWOPI * f * tt + 3.0 * np.sin(TWOPI * f * 1.41 * tt))
        elif kind == 'sh':          # sample-and-hold ("bit-crushed") noise, rendered 4x then decimated
            hold = int(rng.integers(6, 40)) * os_
            src = noise(m * os_ // hold + 2, seed * 31 + 100 + k)
            y = decimate(np.repeat(src, hold)[: m * os_], os_)[:m] * 0.7
        else:
            y = np.zeros(m)
        rr = min(m // 2, smp(0.0006))
        y[:rr] *= rc_ramp(rr)
        y[m - rr:] *= rc_ramp(rr)[::-1]
        p = float(rng.uniform(-0.7, 0.7))
        s0 = smp(t)
        e = min(n, s0 + m)
        out[:, s0:e] += stereo(y[: e - s0], p)
        t += seg
        k += 1
    return out


