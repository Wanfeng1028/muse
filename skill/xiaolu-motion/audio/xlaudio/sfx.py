def _ui_click(rng, seed, pitch=0.0, bright=0.5, dur=0.03):
    r = semis(pitch)
    n = smp(dur + 0.012)
    t = np.arange(n) / SR
    hi = min((3500.0 + 7000.0 * bright) * r, 20000.0)
    nz = bpf(noise(n, seed * 13 + 1), 1500.0 * r, hi) * _att(t, 0.0002) * np.exp(-t / 0.0012)
    tone = np.sin(TWOPI * 3400.0 * r * t) * _att(t, 0.0003) * np.exp(-t / max(0.001, dur * 0.1))
    body = np.sin(TWOPI * 220.0 * r * t) * _att(t, 0.0008) * np.exp(-t / max(0.002, dur * 0.2))
    return 0.8 * nz + (0.2 + 0.3 * bright) * tone + 0.3 * body


