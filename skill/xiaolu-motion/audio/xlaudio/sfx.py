def _reverse_whoosh(rng, seed, pitch=0.0, bright=0.5, dur=0.8, width=0.8):
    r = semis(pitch)
    f_hi = min(2600.0 * r * _b(bright), 12000.0)
    a = ins.whoosh(dur, 320.0 * r, f_hi, 'reverse', q=0.9, pan0=-width, pan1=0.0, seed=seed * 7 + 3,
                   lowmix=0.6, fade_out=0.004, air=0.3 * bright)
    b = ins.whoosh(dur, 330.0 * r, f_hi * 1.04, 'reverse', q=0.9, pan0=width, pan1=0.0, seed=seed * 7 + 5,
                   lowmix=0.6, fade_out=0.004, air=0.3 * bright)
    return 0.5 * (a + b)


