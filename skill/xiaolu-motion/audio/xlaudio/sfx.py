def catalog_rows(family=None):
    rows = []
    for sid in list_sfx(family):
        s = REGISTRY[sid]
        y = render_sfx(sid, seed=0)
        rows.append(dict(id=sid, family=s.family, purpose=s.purpose, sync=s.sync, anchor=s.anchor,
                         ref='%s %.1f %s' % ('TP' if s.ref[0] == 'tp' else 'M-max', s.ref[1],
                                             'dBTP' if s.ref[0] == 'tp' else 'LUFS'),
                         default_len=y.shape[1] / SR, params=s.params, notes=s.notes, aliases=s.aliases))
    return rows
