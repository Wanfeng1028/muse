def _pop_soft(rng, seed, pitch=0.0, bright=0.5, dur=0.12):
    r = semis(pitch)
    n = smp(dur + 0.02)
    t = np.arange(n) / SR
    f = 420.0 * r * (1.0 + 1.1 * (1.0 - np.exp(-t / 0.010)))
    ph = TWOPI * np.cumsum(f) / SR
    env = _att(t, 0.0015) * np.exp(-t / (dur * 0.3))
    y = np.sin(ph) * env + 0.15 * bright * np.sin(2 * ph) * env
    click = bpf(noise(n, seed * 17 + 2), 2000.0 * r, min(6500.0 * r, 20000.0)) * _att(t, 0.0002) * np.exp(-t / 0.0015)
    return y + 0.25 * bright * click


