# =============================================================================
# registry
# =============================================================================
@dataclass
class SfxSpec:
    id: str
    fn: object                      # fn(rng, seed, **params) -> (n,) or (2, n)
    purpose: str                    # 用途
    sync: str                       # 建议对位
    anchor: str                     # 'start' | 'peak' | 'end' | 'mark'
    ref: tuple                      # ('tp', dBTP) or ('mmax', LUFS)
    params: dict                    # name -> (default, lo, hi, note)
    family: str = 'sfx'             # 'sfx' | 'ident'
    humanize_db: float = 0.0        # random level spread (+-dB) applied after normalisation
    lead_frames: float = 0.0        # align='motion': sound starts this many frames before the visual action
    mark_s: object = None           # callable(params) -> seconds, for anchor == 'mark'
    notes: str = ''
    aliases: tuple = field(default_factory=tuple)


REGISTRY = {}
ALIASES = {}


def register(spec):
    REGISTRY[spec.id] = spec
    for a in spec.aliases:
        ALIASES[a] = spec.id
    return spec


def list_sfx(family=None):
    return [k for k, s in REGISTRY.items() if family is None or s.family == family]


def get_spec(sfx_id):
    sid = ALIASES.get(sfx_id, sfx_id)
    if sid not in REGISTRY:
        raise KeyError('unknown sfx id %r (known: %s)' % (sfx_id, ', '.join(sorted(REGISTRY))))
    return REGISTRY[sid]


def _resolve(spec, params):
    out = {}
    for k, v in params.items():
        if k not in spec.params:
            raise TypeError('%s: unknown parameter %r (allowed: %s)' % (spec.id, k, ', '.join(spec.params)))
    for k, (default, lo, hi, _) in spec.params.items():
        v = params.get(k, default)
        if lo is not None and isinstance(v, (int, float, np.floating)) and not isinstance(v, bool):
            if v < lo or v > hi:
                warnings.warn('%s: %s=%r outside [%r, %r], clipped' % (spec.id, k, v, lo, hi), stacklevel=3)
                v = min(max(v, lo), hi)
        out[k] = v
    return out


def _finish(y, spec, seed, normalize=True, gain_db=0.0):
    y = np.asarray(y, dtype=np.float64)
    if y.ndim == 1:
        y = dual_mono(y)
    # DC-safe: 20 ms of silence lets the 12 Hz high-pass settle, then trim + fade
    n = y.shape[1]
    y = dc_block(np.hstack([y, np.zeros((2, smp(0.02)))]))[:, :n]
    y = fade_edges(y, 0.0003, 0.003)
    if normalize:
        kind, target = spec.ref
        lvl = meter.true_peak_db(y) if kind == 'tp' else meter.max_momentary(y)
        if np.isfinite(lvl):
            y = y * db2lin(target - lvl)
    if spec.humanize_db > 0:
        r = np.random.default_rng(zlib.crc32(('%s|%d|lvl' % (spec.id, seed)).encode()))
        y = y * db2lin(r.uniform(-spec.humanize_db, spec.humanize_db))
    if gain_db:
        y = y * db2lin(gain_db)
    return y


def render_sfx(sfx_id, seed=0, normalize=True, gain_db=0.0, **params):
    """Render one sound effect -> float64 (2, n) at 48 kHz, starting and ending
    at digital zero, normalised to the class reference level (unless
    normalize=False). Unknown parameters raise TypeError; out-of-range values
    are clipped with a warning."""
    spec = get_spec(sfx_id)
    p = _resolve(spec, params)
    rng = np.random.default_rng(zlib.crc32(('%s|%d' % (spec.id, int(seed))).encode()))
    y = spec.fn(rng, int(seed), **p)
    return _finish(y, spec, int(seed), normalize, gain_db)


def anchor_offset(sfx_id, y, mode=None, **params):
    """sample offset of the effect's sync point inside a rendered buffer
    (mode overrides the class anchor: 'start' | 'end' | 'peak' | 'mark')."""
    spec = get_spec(sfx_id)
    mode = mode or spec.anchor
    if mode == 'start':
        return 0
    if mode == 'end':
        return y.shape[1]
    if mode == 'mark' and spec.mark_s is not None:
        p = _resolve(spec, params)
        return smp(spec.mark_s(p))
    # 'peak': maximum of the 10 ms RMS envelope
    e = np.sum(y * y, axis=0)
    w = smp(0.010)
    c = np.concatenate([[0.0], np.cumsum(e)])
    r = c[w:] - c[:-w]
    return int(np.argmax(r) + w // 2)


