def _sub_drop(rng, seed, pitch=0.0, bright=0.5, dur=1.4):
    r = semis(pitch)
    n = smp(dur)
    t = np.arange(n) / SR
    f = 32.0 * r + (88.0 * r - 32.0 * r) * np.exp(-t / (0.28 * dur))
    y = np.sin(TWOPI * np.cumsum(f) / SR) * _att(t, 0.004) * np.exp(-t / (0.45 * dur))
    sat = 1.0 + 2.0 * bright
    return np.tanh(sat * y) / np.tanh(sat)


