_WHOOSH = {
    'fast': dict(dur=0.30, f_lo=700.0, f_hi=3600.0, peak=0.42, q=1.3, travel=0.7, dmin=0.15, dmax=0.5),
    'mid': dict(dur=0.60, f_lo=380.0, f_hi=2600.0, peak=0.55, q=1.2, travel=0.6, dmin=0.35, dmax=1.0),
    'slow': dict(dur=1.20, f_lo=240.0, f_hi=1900.0, peak=0.60, q=1.0, travel=0.5, dmin=0.8, dmax=3.0),
}


def _whoosh_fn(speed):
    base = _WHOOSH[speed]

    def fn(rng, seed, pitch=0.0, bright=0.5, dur=base['dur'], travel=base['travel'], peak=base['peak']):
        r = semis(pitch)
        f_lo = base['f_lo'] * r
        f_hi = min(base['f_hi'] * r * _b(bright), 12000.0)
        pk = float(peak)

        def fc_curve(u):              # rises with the swell, falls ~40 % back after the peak (pass-by)
            up = np.clip(u / pk, 0, 1) ** 1.2
            down = np.clip((u - pk) / (1 - pk), 0, 1) ** 0.8
            return up - 0.4 * down

        return ins.whoosh(dur, f_lo, f_hi, 'swell', q=base['q'], pan0=-travel, pan1=travel, seed=seed * 7 + 11,
                          lowmix=0.35, fade_out=0.006, peak=pk, fc_curve=fc_curve, air=0.25 * bright)
    return fn


