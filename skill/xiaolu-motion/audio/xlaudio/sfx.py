def _clack(rng, seed, pitch=0.0, bright=0.5, zap=0.0):
    r = semis(pitch)
    y = ins.clack(1.0, seed=seed * 47 + 1, f=900.0 * r)
    if bright != 0.5:
        y = y + (bright - 0.5) * 0.6 * hp(y, 3000, 2)
    if zap > 0:
        z = ins.zap(1.0, 1600.0 * r, 150.0 * r)
        m = max(len(y), len(z))
        y = np.pad(y, (0, m - len(y))) + 0.55 * zap * np.pad(z, (0, m - len(z)))
    return y


