function dur(f) {
  try { execFileSync(FF, ['-hide_banner','-i',f], { encoding:'utf8', stdio:['ignore','pipe','pipe'] }); }
  catch (e) {
    const m = String(e.stderr||'').match(/Duration: (\d+):(\d+):([\d.]+)/);
    return m ? +m[1]*3600 + +m[2]*60 + +m[3] : 0;
  }
  return 0;
}
